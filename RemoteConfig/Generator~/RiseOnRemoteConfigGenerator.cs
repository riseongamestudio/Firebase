using System.IO;
using System.Linq;
using System.Security;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace RiseOn.Firebase.RemoteConfig.Generator {
    /// <summary>
    /// Compiles into RiseOn.Firebase.RemoteConfig the parameters the settings page lists: the enum RemoteKey, numbered by each parameter's id, and a typed property per key on RemoteKeys.<br/>
    /// Both are named by the key as written, with @ before a C# keyword, so any key the console takes has its name in code.<br/>
    /// Nothing is written to disk, so nobody can edit it.
    /// </summary>
    [Generator]
    public sealed class RiseOnRemoteConfigGenerator : ISourceGenerator {
        private const string PackAssembly = "RiseOn.Firebase.RemoteConfig";
        private const string KeysFile     = ".RiseOnRemoteConfigGenerator.additionalfile";

        private static readonly string[] types = { "bool", "int", "float", "string" };

        private static readonly DiagnosticDescriptor badLine = new(
            "RISEONRC001", "Unreadable key line", "{0} line {1} is not 'id, key, type, description' split by tabs; open Project Settings > RiseOn > Firebase > Remote Config to write it again",
            "RiseOn.Firebase.RemoteConfig", DiagnosticSeverity.Error, true);

        public void Initialize(GeneratorInitializationContext context) { }

        public void Execute(GeneratorExecutionContext context) {
            if (context.Compilation.AssemblyName is not PackAssembly) return;

            var members    = new StringBuilder();
            var properties = new StringBuilder();
            foreach (var file in context.AdditionalFiles.Where(file => file.Path.EndsWith(KeysFile))) {
                var lines = file.GetText(context.CancellationToken)?.Lines;
                if (lines == null) continue;

                for (var i = 0; i < lines.Count; ++i) {
                    var line = lines[i].ToString();
                    if (line.Trim().Length == 0) continue;

                    var parts = line.Split('\t');
                    if (parts.Length != 4 || !int.TryParse(parts[0], out var id) || id <= 0 || !SyntaxFacts.IsValidIdentifier(parts[1]) || !types.Contains(parts[2])) {
                        context.ReportDiagnostic(Diagnostic.Create(badLine, Location.None, Path.GetFileName(file.Path), i + 1));
                        continue;
                    }

                    // The description shows on both, for code that reads a value and for code that picks a key.
                    var summary = parts[3].Length > 0 ? $"        /// <summary>{SecurityElement.Escape(parts[3])}</summary>\n" : "";
                    var name    = SyntaxFacts.GetKeywordKind(parts[1]) is SyntaxKind.None ? parts[1] : "@" + parts[1];
                    members.Append(summary);
                    members.Append($"        {name} = {id},\n");
                    properties.Append(summary);
                    // A static class still inherits object's members, which a key of that name hides.
                    var hides = parts[1] is "Equals" or "ReferenceEquals" or "ToString" or "GetType" or "GetHashCode" or "MemberwiseClone" ? "new " : "";
                    // Named in full, so a key named after one of the pack's types does not hide it from the other properties.
                    properties.Append($"        public {hides}static global::RiseOn.Firebase.RemoteConfig.RemoteValue<{parts[2]}> {name} => global::RiseOn.Firebase.RemoteConfig.RemoteValues.Get<{parts[2]}>({id});\n\n");
                }
            }

            var code = new StringBuilder();
            code.Append("// <auto-generated/>\n");
            code.Append("namespace RiseOn.Firebase.RemoteConfig {\n");
            code.Append("    /// <summary>The keys of Project Settings > RiseOn > Firebase > Remote Config.</summary>\n");
            code.Append("    public enum RemoteKey {\n");
            code.Append(members);
            code.Append("    }\n\n");
            code.Append("    public static partial class RemoteKeys {\n");
            code.Append(properties);
            code.Append("    }\n}\n");
            context.AddSource("RemoteKeys.g.cs", SourceText.From(code.ToString(), Encoding.UTF8));
        }
    }
}